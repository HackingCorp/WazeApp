/**
 * Get a translated string with variable interpolation.
 * Falls back to English if the language is not supported.
 */
export function t(lang: string, key: string, vars?: Record<string, string | number>): string {
  const language = (lang === 'fr' ? 'fr' : 'en') as EmailLanguage;
  let text = emailTranslations[language]?.[key] || emailTranslations.en[key] || key;

  if (vars) {
    for (const [varName, value] of Object.entries(vars)) {
      text = text.replace(new RegExp(`\\{${varName}\\}`, 'g'), String(value));
    }
  }

  return text;
}
